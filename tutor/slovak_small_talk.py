"""
tutor/slovak_small_talk.py - the Slovak small talk course: A1 to A2 in 7 weeks.

A second Slovak course, next to the intensive one: Slovak learned through
SMALL TALK - the short, friendly conversations people have every day with a
neighbour, a colleague at the coffee machine or a guest at a party: how are
you, the weather, work, the weekend, plans, news, compliments and a polite
goodbye.

The method is one rule, practised in every lesson: never give a one-word
answer. React first (Naozaj? Super! Škoda.), answer, add one small detail and
send the question back (A ty?). The "Longer sentences" part of each lesson
shows one short answer growing into that full small talk turn.

Weeks 1-2 are A1 (explained in simple English), weeks 3-7 are A2 (explained
in simple Slovak). Weeks 5-7 take the same method into real places: a café,
a shop, the market, the bus, the university, a new job, the dorm, the barber,
the gym, the train and a waiting room. Every item is (Slovak, English, Azerbaijani); the learner
is a man, so the examples use the masculine forms.
"""
from __future__ import annotations


def _items(rows: list[tuple[str, str, str]]) -> list[dict]:
    return [{"text": sk, "meaning": en, "native": az} for sk, en, az in rows]


def _lesson(lid: str, week: int, day: int, band: str, title: str, goal: str,
            words: list, phrases: list, grammar: dict, partner_role: str,
            dialogue: list, extend: list, translate: list, questions: list, speak: str,
            skills: list[str] | None = None) -> dict:
    return {
        "id": lid, "week": week, "day": day, "band": band, "title": title, "goal": goal,
        "words": _items(words), "phrases": _items(phrases),
        "grammar": dict(grammar, skills=skills or []),
        "partner_role": partner_role,
        "dialogue": [{"who": who, "text": sk, "meaning": en} for who, sk, en in dialogue],
        # One short answer, growing into a full small talk turn: (the sentence now, what was added).
        "extend": [[{"text": text, "how": how} for text, how in extend]],
        "translate": [{"en": en, "sk": sk} for en, sk in translate],
        "questions": [{"q": q, "meaning": en, "example": ex} for q, en, ex in questions],
        "speak": speak,
    }


